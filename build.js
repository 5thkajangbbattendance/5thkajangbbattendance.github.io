// Builds index.html (the page GitHub Pages serves) from app.html.
// Run after editing app.html:  node build.js
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const FIREBASE = 'https://cdn.jsdelivr.net/npm/firebase@10.12.5';
const app = fs.readFileSync(path.join(__dirname, 'app.html'), 'utf8');
const html = '<!doctype html><html lang="en-MY"><head><meta charset="utf-8">' +
  '<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><meta name="theme-color" content="#14294f">' +
  ['app', 'auth', 'firestore'].map(n => `<script src="${FIREBASE}/firebase-${n}-compat.js"></script>`).join('') +
  '<script src="firebase-config.js"></script></head><body>\n<!-- Generated by build.js from app.html. Edit app.html, then run: node build.js -->\n' +
  app + '</body></html>\n';
fs.writeFileSync(path.join(__dirname, 'index.html'), html);
console.log('Wrote index.html');
