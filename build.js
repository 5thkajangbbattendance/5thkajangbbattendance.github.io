// Builds the two pages GitHub Pages serves:
//   index.html             public website   (from site.html)
//   attendance/index.html  staff app        (from app.html)
//   uniform/index.html     uniform order    (from uniform.html)
//   form/index.html        public form      (from form.html)
//   notices/index.html     notice board     (from notices.html)
// Run after editing site.html, app.html or uniform.html:  node build.js
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const FIREBASE = 'https://cdn.jsdelivr.net/npm/firebase@10.12.5';
const sdk = (names, prefix) => names.map(n => `<script src="${FIREBASE}/firebase-${n}-compat.js"></script>`).join('') + `<script src="${prefix}firebase-config.js"></script>`;
const SITE_URL = 'https://5thkajangbbattendance.github.io/';
const attr = s => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;');
/* The page's own <title> and description move up into <head>, with the preview tags WhatsApp, Facebook and search engines read. */
const shell = (head, body, note, color, share) => {
  let title = '', desc = '';
  body = body.replace(/^\s*<title>([^<]*)<\/title>\s*/, (m, t) => { title = t; return ''; });
  body = body.replace(/<meta name="description" content="([^"]*)">\s*/, (m, d) => { desc = d; return ''; });
  let meta = (title ? '<title>' + title + '</title>' : '') + (desc ? '<meta name="description" content="' + desc + '">' : '');
  if (share) meta += '<meta property="og:type" content="website"><meta property="og:site_name" content="The 5th Kajang Boys’ Brigade">' +
    '<meta property="og:title" content="' + attr(share.title || title) + '"><meta property="og:description" content="' + desc + '">' +
    (share.path != null ? '<meta property="og:url" content="' + SITE_URL + share.path + '"><link rel="canonical" href="' + SITE_URL + share.path + '">' : '') + '<meta property="og:image" content="' + SITE_URL + 'img/site/company-church.jpg">' +
    '<meta property="og:image:width" content="960"><meta property="og:image:height" content="924"><meta property="og:image:alt" content="Members of the 5th Kajang Company in uniform at Kajang Chinese Methodist Church">' +
    '<meta name="twitter:card" content="summary_large_image">';
  return '<!doctype html><html lang="en-MY"><head><meta charset="utf-8">' +
    '<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><meta name="color-scheme" content="light dark"><meta name="theme-color" content="' + (color || '#0f6e5f') + '">' +
    meta + head + '</head><body>\n<!-- Generated by build.js from ' + note + '. Edit that file, then run: node build.js -->\n' + body + '</body></html>\n';
};

const site = fs.readFileSync(path.join(__dirname, 'site.html'), 'utf8');
fs.writeFileSync(path.join(__dirname, 'index.html'),
  shell('<link rel="icon" href="bb-crest.png"><link rel="apple-touch-icon" href="bb-crest.png">' + sdk(['app', 'firestore'], ''), site, 'site.html', '#0b1736', { title: 'The 5th Kajang Boys’ Brigade', path: '' }));

const app = fs.readFileSync(path.join(__dirname, 'app.html'), 'utf8').replace(/src="bb-crest\.png"/g, 'src="../bb-crest.png"');
fs.mkdirSync(path.join(__dirname, 'attendance'), { recursive: true });
fs.writeFileSync(path.join(__dirname, 'attendance', 'index.html'),
  shell('<link rel="icon" href="../bb-crest.png"><link rel="apple-touch-icon" href="../bb-crest.png"><meta name="robots" content="noindex"><script>window.BB_ROOT="../"</script>' + sdk(['app', 'auth', 'firestore'], '../'), app, 'app.html', '#0b1736'));
const uni = fs.readFileSync(path.join(__dirname, 'uniform.html'), 'utf8').replace(/src="bb-crest\.png"/g, 'src="../bb-crest.png"');
fs.mkdirSync(path.join(__dirname, 'uniform'), { recursive: true });
fs.writeFileSync(path.join(__dirname, 'uniform', 'index.html'),
  shell('<link rel="icon" href="../bb-crest.png"><link rel="apple-touch-icon" href="../bb-crest.png"><script>window.BB_ROOT="../"</script>' + sdk(['app', 'firestore'], '../'), uni, 'uniform.html', '#0b1736', { path: 'uniform/' }));
for (const [src, dir, robots, share] of [['form.html', 'form', true, {}], ['notices.html', 'notices', false, { path: 'notices/' }]]) {
  const page = fs.readFileSync(path.join(__dirname, src), 'utf8').replace(/src="bb-crest\.png"/g, 'src="../bb-crest.png"');
  fs.mkdirSync(path.join(__dirname, dir), { recursive: true });
  fs.writeFileSync(path.join(__dirname, dir, 'index.html'),
    shell('<link rel="icon" href="../bb-crest.png"><link rel="apple-touch-icon" href="../bb-crest.png">' + (robots ? '<meta name="robots" content="noindex">' : '') + '<script>window.BB_ROOT="../"</script>' + sdk(['app', 'firestore'], '../'), page, src, '#0b1736', share));
}
console.log('Wrote index.html, attendance/, uniform/, form/ and notices/');
